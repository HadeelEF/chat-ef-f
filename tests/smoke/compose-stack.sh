#!/usr/bin/env bash
# End-to-end smoke test of the Docker Compose stacks (infrastructure/compose), run against real containers with
# throwaway secrets and synthetic identities. Everything it creates is removed at the end.
#   local   compose.yaml + compose.local.yaml   (Windows 11 / workstation profile: loopback HTTP only)
#   onprem  compose.yaml + compose.onprem.yaml  (Ubuntu Server profile: Caddy HTTPS reverse proxy, TLS "internal")
# Checks: startup, health, MongoDB and Meilisearch auth and isolation, registration policy, first-admin bootstrap, search
# enabled, the Admin Panel (ADR-0016: entry point, isolation, admin-only API, drift check), persistence across
# restarts, backup/restore after losing every volume, secret hygiene; on-prem adds TLS, redirect, headers, exposure.
# (Formerly tests/smoke/m1-stack.sh — T01–T35 keep their M1 meaning.)
#
# Usage: tests/smoke/compose-stack.sh [local|onprem] [results-file]
# Needs: docker with compose >= 2.24, curl, python3, openssl. Exit 0 when every check passes.
# Results are cloud-session evidence, not independent CI.
set -uo pipefail

mode="${1:-local}"
[[ "$mode" == local || "$mode" == onprem ]] || { echo "usage: $0 [local|onprem] [results-file]" >&2; exit 2; }
root="$(git rev-parse --show-toplevel)"
stack="$root/infrastructure/compose"
results="${2:-/dev/null}"
source "$(dirname "${BASH_SOURCE[0]}")/../lib.sh" # log, check, failures/total, summary
project="efaiw-smoke-$mode-$$"
port="${SMOKE_HTTP_PORT:-3399}"; https_port="${SMOKE_HTTPS_PORT:-3443}"; admin_port="${SMOKE_ADMIN_PORT:-3398}"
work="$(mktemp -d)"
env_file="$work/.env"
host="efaiw-onprem.test"; admin_host="admin.efaiw-onprem.test"
if [[ "$mode" == local ]]; then
  override="compose.local.yaml"; base="http://127.0.0.1:$port"; admin_base="http://127.0.0.1:$admin_port"
  services="admin-panel=healthy librechat=healthy meilisearch=healthy mongodb=healthy "
  curl_opts=()
else
  override="compose.onprem.yaml"; base="https://$host:$https_port"; admin_base="https://$admin_host:$https_port"
  services="admin-panel=healthy librechat=healthy meilisearch=healthy mongodb=healthy proxy=healthy "
  curl_opts=(--resolve "$host:$https_port:127.0.0.1" --resolve "$host:$port:127.0.0.1" --resolve "$admin_host:$https_port:127.0.0.1"
             --cacert "$work/caddy-root.crt")
fi

dc() { docker compose -p "$project" -f "$stack/compose.yaml" -f "$stack/$override" --env-file "$env_file" "$@"; }
ctr() { dc ps -q "$1"; }
anon_volumes() { # anonymous volumes of this stack's containers (e.g. mongo's /data/configdb), orphaned by down + up
  local c; for c in $(dc ps -aq); do
    docker inspect -f '{{range .Mounts}}{{if eq .Type "volume"}}{{.Name}}{{"\n"}}{{end}}{{end}}' "$c"
  done | grep -E '^[0-9a-f]{64}$' >> "$work/anon-volumes" || true
}
cleanup() { anon_volumes; dc down -v --remove-orphans >/dev/null 2>&1
            sort -u "$work/anon-volumes" 2>/dev/null | xargs -r docker volume rm >/dev/null 2>&1; rm -rf "$work"; }
trap cleanup EXIT

wait_healthy() { # all services healthy within ~4 minutes
  local states=""
  for _ in $(seq 1 48); do
    states="$(dc ps --format '{{.Service}}={{.Health}}' | sort | tr '\n' ' ')"
    [[ "$states" == "$services" ]] && return 0
    sleep 5
  done
  echo "not healthy: $states"; return 1
}
fetch_ca() { # on-prem: trust Caddy's internal root CA explicitly (no -k anywhere)
  [[ "$mode" == onprem ]] || return 0
  docker exec "$(ctr proxy)" cat /data/caddy/pki/authorities/local/root.crt > "$work/caddy-root.crt"
}
c() { curl -s --noproxy "*" "${curl_opts[@]}" "$@"; } # never via an HTTP(S)_PROXY from the environment
http_code() { c -o /dev/null -w '%{http_code}' "$@"; }
login() { # <email> <password> -> prints role on success
  c -f -X POST "$base/api/auth/login" -H 'Content-Type: application/json' \
    -d "{\"email\":\"$1\",\"password\":\"$2\"}" | python3 -c 'import sys,json; print(json.load(sys.stdin)["user"]["role"])'
}
mongo_eval() { # <js> as the application user
  docker exec "$(ctr mongodb)" sh -c 'mongosh --quiet --norc "mongodb://127.0.0.1:27017/$MONGO_APP_DATABASE" \
    -u "$MONGO_APP_USERNAME" -p "$MONGO_APP_PASSWORD" --authenticationDatabase "$MONGO_APP_DATABASE" --eval "$0"' "$1"
}
create_user() { # <email> <name> <username> <password>
  printf '%s\n' "$4" | docker exec -i "$(ctr librechat)" npm run --silent create-user -- "$1" "$2" "$3" --email-verified=true
}

# --- throwaway configuration (never written to the repository), generated by the same script users run ---
if [[ "$mode" == local ]]; then
  "$root/scripts/setup/new-env.sh" local --port "$port" --admin-port "$admin_port" --output "$env_file" >/dev/null
  sed -i -e "s|^DOMAIN_\(CLIENT\|SERVER\)=.*|DOMAIN_\1=$base|" -e "s|^ADMIN_PANEL_URL=.*|ADMIN_PANEL_URL=$admin_base|" "$env_file"
else
  "$root/scripts/setup/new-env.sh" onprem --hostname "$host" --admin-hostname "$admin_host" --tls internal --output "$env_file" >/dev/null
  sed -i -e "s|^DOMAIN_\(CLIENT\|SERVER\)=.*|DOMAIN_\1=$base|" -e "s|^ADMIN_PANEL_URL=.*|ADMIN_PANEL_URL=$admin_base|" "$env_file"
  printf 'EFAIW_BIND_ADDRESS=127.0.0.1\nEFAIW_HTTP_PORT=%s\nEFAIW_HTTPS_PORT=%s\nEFAIW_TLS_DIR=%s\n' "$port" "$https_port" "$work/tls" >> "$env_file"
fi
admin_email="synthetic.admin@example.invalid"; admin_pw="$(openssl rand -hex 12)"
user_email="synthetic.user@example.invalid";   user_pw="$(openssl rand -hex 12)"
reg_email="synthetic.reg@example.invalid";     reg_pw="Aa1!$(openssl rand -hex 8)"

log "# Compose smoke test ($mode)  commit=$(git -C "$root" rev-parse --short=12 HEAD)  date=$(date -u +%FT%TZ)  docker=$(docker version --format '{{.Server.Version}}')  compose=$(docker compose version --short)"

# ---------------------------------------------------------------- checks (each is a function; non-zero = FAIL)
t_config()        { dc config --quiet; }
t_config_guard()  { local out; out="$(docker compose -f "$stack/compose.yaml" -f "$stack/$override" --env-file /dev/null config --quiet 2>&1)" && return 1
                    [[ "$out" == *"required variable"* ]] || { echo "$out"; return 1; }; }
t_pinned() {
  local svc cfg id svcs=(admin-panel librechat meilisearch mongodb); [[ "$mode" == onprem ]] && svcs+=(proxy)
  for svc in "${svcs[@]}"; do
    cfg="$(docker inspect -f '{{.Config.Image}}' "$(ctr "$svc")")"; id="$(docker inspect -f '{{.Image}}' "$(ctr "$svc")")"
    [[ "$cfg" == *"@${id}" ]] || { echo "$svc: configured $cfg, running $id"; return 1; }
  done
}
t_no_startup_errors() { local errs; errs="$(dc logs librechat 2>&1 | sed 's/\x1b\[[0-9;]*m//g' | grep -E ' error: ' || true)"
                        [[ -z "$errs" ]] || { echo "$errs" | head -3; return 1; }; }
t_version()       { [[ "$(docker exec "$(ctr librechat)" node -p "require('/app/package.json').version")" == v0.8.8 ]]; }
t_policy_env()    { # infrastructure/common/librechat.env reaches the container unchanged
  local k v line; while IFS='=' read -r k v; do
    line="$(docker exec "$(ctr librechat)" printenv "$k" 2>/dev/null)"; [[ "$line" == "$v" ]] || { echo "$k=$line (expected $v)"; return 1; }
  done < <(grep -E '^[A-Z_]+=' "$root/infrastructure/common/librechat.env")
}
t_mongo_noauth()  { ! docker exec "$(ctr mongodb)" mongosh --quiet --norc --eval 'db.getSiblingDB("LibreChat").getCollectionNames()'; }
t_mongo_rw()      { mongo_eval 'db.smoke.insertOne({ ok: 1 }); db.smoke.drop()'; }
t_mongo_otherdb() { ! mongo_eval 'db.getSiblingDB("other").x.insertOne({ a: 1 })'; }
t_mongo_noadmin() { ! mongo_eval 'db.createUser({ user: "x", pwd: "x", roles: [] })'; }
t_health()        { [[ "$(c -f "$base/health")" == OK ]]; }
t_webapp()        { c -f "$base/" | grep -qi '<div id="root"'; }
t_login_page()    { [[ "$(http_code "$base/login")" == 200 ]]; }
t_api_config()    { c -f "$base/api/config" | python3 -c 'import sys,json; c=json.load(sys.stdin)
assert c["registrationEnabled"] is False and c["emailLoginEnabled"] is True and c["socialLoginEnabled"] is False, c'; }
t_register_user() { # ADR-0024: self-registration is refused and creates no account
  local code; code="$(http_code -X POST "$base/api/auth/register" -H 'Content-Type: application/json' \
    -d "{\"name\":\"Synthetic Reg\",\"username\":\"synthreg\",\"email\":\"$reg_email\",\"password\":\"$reg_pw\",\"confirm_password\":\"$reg_pw\"}")"
  [[ "$code" == 403 ]] || { echo "register HTTP $code"; return 1; }
  ! login "$reg_email" "$reg_pw" >/dev/null
}
t_no_users()      { [[ "$(mongo_eval 'db.users.countDocuments()')" == 0 ]]; }
t_bootstrap()     { create_user "$admin_email" "Synthetic Admin" synthadmin "$admin_pw"; }
t_admin_login()   { [[ "$(login "$admin_email" "$admin_pw")" == ADMIN ]]; }
t_second_user()   { create_user "$user_email" "Synthetic User" synthuser "$user_pw" >/dev/null && [[ "$(login "$user_email" "$user_pw")" == USER ]]; }
t_bad_password()  { ! login "$admin_email" wrong-password; }
t_mongo_no_port() { [[ -z "$(docker port "$(ctr mongodb)")" ]]; }
t_app_loopback()  { local p; p="$(docker port "$(ctr librechat)")"; [[ "$p" == "3080/tcp -> 127.0.0.1:$port" ]] || { echo "$p"; return 1; }; }
t_app_private()   { local p; p="$(docker port "$(ctr librechat)")"; [[ -z "$p" ]] || { echo "librechat publishes: $p"; return 1; }; }
t_proxy_ports() {
  local p; p="$(docker port "$(ctr proxy)" | sort | tr '\n' ' ')"
  [[ "$p" == "443/tcp -> 127.0.0.1:$https_port 80/tcp -> 127.0.0.1:$port " ]] || { echo "$p"; return 1; }
}
t_mongo_internal() {
  local nets; nets="$(docker inspect -f '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}' "$(ctr mongodb)")"
  [[ "$nets" == "${project}_backend " && "$(docker network inspect -f '{{.Internal}}' "${project}_backend")" == true ]] || { echo "$nets"; return 1; }
}
t_proxy_frontend_only() {
  local nets; nets="$(docker inspect -f '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}' "$(ctr proxy)")"
  [[ "$nets" == "${project}_frontend " ]] || { echo "$nets"; return 1; }
}
t_mongo_no_egress() { ! docker exec "$(ctr mongodb)" timeout 5 bash -c 'exec 3<>/dev/tcp/1.1.1.1/443'; }
t_meili_private() { # conversation search (#125): no host port, internal backend network only
  local p nets; p="$(docker port "$(ctr meilisearch)")"
  nets="$(docker inspect -f '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}' "$(ctr meilisearch)")"
  [[ -z "$p" && "$nets" == "${project}_backend " ]] || { echo "ports=$p nets=$nets"; return 1; }
}
t_meili_key() { # without the master key Meilisearch answers 401; LibreChat reaches it with the key
  local js='const h = process.env.MEILI_HOST, k = process.env.MEILI_MASTER_KEY;
    Promise.all([fetch(h + "/indexes"), fetch(h + "/indexes", { headers: { Authorization: "Bearer " + k } })])
      .then(r => console.log(r.map(x => x.status).join(" "))).catch(e => console.log(e.message))'
  local out; out="$(docker exec "$(ctr librechat)" node -e "$js")"; [[ "$out" == "401 200" ]] || { echo "$out"; return 1; }
}
t_meili_no_egress() { ! docker exec "$(ctr meilisearch)" timeout 5 wget -q -T 3 -O /dev/null http://1.1.1.1/; }
t_search_enabled() { # the web client shows the search box only when /api/search/enable is true (Meilisearch healthy)
  local token; token="$(c -f -X POST "$base/api/auth/login" -H 'Content-Type: application/json' \
    -d "{\"email\":\"$admin_email\",\"password\":\"$admin_pw\"}" | python3 -c 'import sys,json; print(json.load(sys.stdin)["token"])')"
  [[ "$(c -f "$base/api/search/enable" -H "Authorization: Bearer $token")" == true ]]
}
t_outsider_blocked() {
  local ip img; ip="$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "$(ctr mongodb)")"
  img="$(docker inspect -f '{{.Image}}' "$(ctr mongodb)")"
  ! docker run --rm --network bridge --entrypoint timeout "$img" 5 bash -c "exec 3<>/dev/tcp/$ip/27017"
}
t_tls_verified()  { c -f -o /dev/null "$base/health"; } # curl verifies the chain against Caddy's root and the hostname
t_tls_hostname()  { ! curl -s --noproxy "*" -o /dev/null --cacert "$work/caddy-root.crt" --resolve "wrong.test:$https_port:127.0.0.1" "https://wrong.test:$https_port/health"; }
t_http_redirect() {
  local hdr; hdr="$(c -s -o /dev/null -D - "http://$host:$port/health")"
  grep -qiE '^HTTP/[0-9.]+ 30[18]' <<<"$hdr" && grep -qi "^location: https://$host" <<<"$hdr" || { echo "$hdr" | head -3; return 1; }
}
t_headers() {
  local hdr; hdr="$(c -s -o /dev/null -D - "$base/health")"
  grep -qi '^strict-transport-security: max-age=31536000' <<<"$hdr" || { echo "no HSTS"; return 1; }
  grep -qi '^x-content-type-options: nosniff' <<<"$hdr" || { echo "no nosniff"; return 1; }
  ! grep -qi '^server:' <<<"$hdr" || { echo "Server header present"; return 1; }
}
t_file_logs() { # LibreChat writes its file logs into the logs volume (/app/logs)
  [[ -n "$(docker exec "$(ctr librechat)" find /app/logs -name '*.log' -size +0)" ]]
}
t_marker() { # markers in two persistent volumes: uploads (user files) and data (violations/plugin state)
  local f
  for f in /app/uploads/smoke-marker.txt /app/data/smoke-marker.txt; do
    [[ "$(docker exec "$(ctr librechat)" cat "$f")" == synthetic-marker ]] || { echo "missing or wrong: $f"; return 1; }
  done
}
t_backup()        { "$root/scripts/operations/backup.sh" "$(ctr mongodb)" "$(ctr librechat)" "$work/backups"; }
t_restore()       { "$root/scripts/operations/restore.sh" "$(ctr mongodb)" "$(ctr librechat)" "$(ls -d "$work"/backups/*/ | head -1)"; }
t_restored_data() { [[ "$(mongo_eval 'db.users.countDocuments()')" == 3 \
                    && "$(mongo_eval 'db.users.countDocuments({ email: "post.backup@example.invalid" })')" == 0 ]]; }
t_panel_health()   { [[ "$(c -f "$admin_base/health")" == ok ]]; }
t_panel_login()    { c -fL "$admin_base/login" | grep -aq '<title>LibreChat Admin Panel</title>'; } # /login redirects to /login?redirect=%2F
t_panel_metrics()  { [[ "$(http_code "$admin_base/metrics")" == 401 ]]; }
t_panel_network() { # frontend only (never MongoDB/Meilisearch); a loopback port locally, no host port on-prem
  local p nets; p="$(docker port "$(ctr admin-panel)")"
  nets="$(docker inspect -f '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}' "$(ctr admin-panel)")"
  [[ "$nets" == "${project}_frontend " ]] || { echo "nets=$nets"; return 1; }
  if [[ "$mode" == local ]]; then [[ "$p" == "3000/tcp -> 127.0.0.1:$admin_port" ]] || { echo "ports=$p"; return 1; }
  else [[ -z "$p" ]] || { echo "ports=$p"; return 1; }; fi
}
t_panel_cookie_policy() { # Secure session cookie behind HTTPS; relaxed only on the loopback HTTP profile
  local v; v="$(docker exec "$(ctr admin-panel)" printenv SESSION_COOKIE_SECURE)"
  [[ "$v" == "$([[ "$mode" == local ]] && echo false || echo true)" ]] || { echo "SESSION_COOKIE_SECURE=$v"; return 1; }
}
t_admin_api() { # LibreChat's admin login: 200 for the administrator, 403 for a USER
  local a u
  a="$(http_code -X POST "$base/api/admin/login/local" -H 'Content-Type: application/json' -d "{\"email\":\"$admin_email\",\"password\":\"$admin_pw\"}")"
  u="$(http_code -X POST "$base/api/admin/login/local" -H 'Content-Type: application/json' -d "{\"email\":\"$user_email\",\"password\":\"$user_pw\"}")"
  [[ "$a $u" == "200 403" ]] || { echo "admin=$a user=$u"; return 1; }
}
t_panel_reaches_api() { # the panel's server reaches LibreChat on the stack network (what every admin action uses)
  [[ "$(docker exec "$(ctr admin-panel)" bun -e 'fetch(process.env.API_SERVER_URL + "/health").then(async r => console.log(await r.text()))')" == OK ]]
}
t_drift_clean()    { "$root/scripts/operations/admin-config-drift.sh" "$(ctr mongodb)"; }
t_admin_headers() { # on-prem: the admin site has the same TLS chain and security headers as the chat site
  local hdr; hdr="$(c -s -o /dev/null -D - "$admin_base/health")" || return 1
  grep -qi '^strict-transport-security: max-age=31536000' <<<"$hdr" && grep -qi '^x-content-type-options: nosniff' <<<"$hdr" &&
    ! grep -qi '^server:' <<<"$hdr" || { echo "$hdr" | head -5; return 1; }
}
t_no_leaks() {
  local logs v; logs="$(dc logs 2>&1)"
  for v in $(grep -E '^(CREDS_KEY|CREDS_IV|JWT_SECRET|JWT_REFRESH_SECRET|MONGO_ROOT_PASSWORD|MONGO_APP_PASSWORD|MEILI_MASTER_KEY|ADMIN_PANEL_SESSION_SECRET)=' "$env_file" | cut -d= -f2) "$admin_pw" "$user_pw"; do
    grep -qF -- "$v" <<<"$logs" && { echo "a secret value appears in logs"; return 1; }
  done
  return 0
}

# ---------------------------------------------------------------- run
check T01 "docker compose config renders with a complete env file" t_config
check T02 "compose refuses to render when required secrets are missing" t_config_guard
dc up -d --quiet-pull >/dev/null 2>&1
check T03 "all services become healthy (healthchecks + depends_on: service_healthy)" wait_healthy
fetch_ca
check T04 "running containers use exactly the digest-pinned images" t_pinned
check T05 "LibreChat reports version v0.8.8" t_version
check T35 "LibreChat startup log contains no ERROR-level lines" t_no_startup_errors
check T36 "shared policy (infrastructure/common/librechat.env) reaches the container unchanged" t_policy_env
check T06 "MongoDB rejects unauthenticated reads" t_mongo_noauth
check T07 "application user can read/write its own database" t_mongo_rw
check T08 "application user cannot write to another database" t_mongo_otherdb
check T09 "application user cannot create users (no admin privileges)" t_mongo_noadmin
check T10 "GET /health returns 200 OK" t_health
check T11 "GET / serves the LibreChat web app shell" t_webapp
check T12 "GET /login returns 200 (login page)" t_login_page
check T13 "/api/config: registration off, email login on, social login off" t_api_config
check T15 "a fresh database has no user before the first administrator" t_no_users
check T16 "create-user bootstraps the first administrator" t_bootstrap
check T17 "first administrator logs in with role ADMIN" t_admin_login
check T41 "conversation search is enabled for a signed-in user (/api/search/enable = true)" t_search_enabled
check T18 "a second created user gets role USER" t_second_user
check T14 "self-registration (POST /api/auth/register) is refused (403) and creates no account" t_register_user
check T19 "wrong password is rejected" t_bad_password
check T20 "no host port is published for MongoDB" t_mongo_no_port
if [[ "$mode" == local ]]; then
  check T21 "LibreChat is published on 127.0.0.1 only (local override)" t_app_loopback
else
  check T21 "LibreChat publishes no host port (only the proxy is exposed)" t_app_private
  check O01 "the proxy publishes exactly 80 and 443 on the configured bind address" t_proxy_ports
  check O02 "the proxy is attached to the frontend network only (cannot reach MongoDB)" t_proxy_frontend_only
  check O03 "HTTPS certificate verifies against the configured CA for the hostname" t_tls_verified
  check O04 "TLS is refused for a hostname that is not configured" t_tls_hostname
  check O05 "HTTP redirects to HTTPS" t_http_redirect
  check O06 "HSTS and nosniff headers are set; Server header removed" t_headers
fi
check T22 "MongoDB is attached only to the internal backend network" t_mongo_internal
check T23 "MongoDB has no outbound internet access" t_mongo_no_egress
check T24 "a container outside the stack cannot reach MongoDB" t_outsider_blocked
check T38 "Meilisearch publishes no host port and is attached only to the internal backend network" t_meili_private
check T39 "Meilisearch refuses requests without its master key (401); LibreChat's key works" t_meili_key
check T40 "Meilisearch has no outbound internet access" t_meili_no_egress
check T37 "LibreChat file logs are written to the logs volume (/app/logs)" t_file_logs
check T42 "Admin Panel answers GET /health = ok through the entry point" t_panel_health
check T43 "Admin Panel serves its sign-in page" t_panel_login
check T44 "Admin Panel is on the frontend network only; loopback port locally, no host port on-prem" t_panel_network
check T45 "Admin Panel /metrics answers 401 (no scrape token configured)" t_panel_metrics
check T46 "Admin Panel session cookie is Secure behind HTTPS, relaxed only on loopback HTTP" t_panel_cookie_policy
check T47 "LibreChat admin login: 200 for the administrator, 403 for a USER" t_admin_api
check T48 "the panel server reaches LibreChat over the stack network" t_panel_reaches_api
check T49 "admin-config-drift.sh passes on a fresh stack (no overrides, no custom roles)" t_drift_clean
[[ "$mode" == onprem ]] && check O07 "the admin site has the verified TLS chain and the same security headers" t_admin_headers

docker exec "$(ctr librechat)" sh -c 'echo synthetic-marker | tee /app/uploads/smoke-marker.txt > /app/data/smoke-marker.txt'
anon_volumes; dc down >/dev/null 2>&1; dc up -d >/dev/null 2>&1
check T25 "stack becomes healthy again after down/up (volumes kept)" wait_healthy
check T26 "administrator still logs in after restart (database persisted)" t_admin_login
check T27 "files in uploads and data volumes persisted across restart" t_marker

check T28 "backup.sh writes database + file archives with checksums" t_backup
create_user "post.backup@example.invalid" "Post Backup" postbackup "$(openssl rand -hex 12)" >/dev/null 2>&1
anon_volumes; dc down -v >/dev/null 2>&1; dc up -d >/dev/null 2>&1
check T29 "fresh stack (all volumes destroyed) becomes healthy" wait_healthy
fetch_ca # a fresh on-prem stack has a new internal CA (its volume was destroyed too)
check T30 "restore.sh restores database and files" t_restore
docker restart "$(ctr librechat)" >/dev/null; wait_healthy >/dev/null
check T31 "administrator logs in after restore" t_admin_login
check T32 "restored data matches the backup point (3 users, post-backup user absent)" t_restored_data
check T33 "files in uploads and data volumes restored" t_marker
check T34 "no secret value appears in container logs" t_no_leaks

summary
exit $((failures > 0))
