#!/usr/bin/env bash
# Generate infrastructure/compose/.env with fresh secrets for one Docker Compose environment (Linux, WSL2, macOS).
# Windows 11: run it inside the Ubuntu WSL2 terminal (docs/operations/windows-local.md).
#
# Usage:
#   scripts/setup/new-env.sh local  [--port 3080] [--admin-port 3000]
#   scripts/setup/new-env.sh onprem --hostname <internal-dns-name> [--admin-hostname <name>] [--tls internal|<email>|"<cert> <key>"]
#   add --output <file> to write elsewhere; an existing file is never overwritten.
#   The Admin Panel (ADR-0016) defaults to http://localhost:3000 locally and https://admin.<hostname> on-prem.
#
# Secrets are generated locally (openssl), written with mode 600 and never printed. Keep CREDS_KEY/CREDS_IV in an
# approved secret store for on-prem environments: losing them makes stored credentials unreadable.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
profile="${1:-}"; shift || true
out="$root/infrastructure/compose/.env"
port=3080; admin_port=3000; hostname=""; admin_hostname=""; tls="/etc/caddy/tls/fullchain.pem /etc/caddy/tls/privkey.pem"

usage() { sed -n '5,10p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2; }
[[ "$profile" == local || "$profile" == onprem ]] || usage
while [[ $# -gt 0 ]]; do
  case "$1" in
    --port) port="$2"; shift 2 ;;
    --admin-port) admin_port="$2"; shift 2 ;;
    --hostname) hostname="$2"; shift 2 ;;
    --admin-hostname) admin_hostname="$2"; shift 2 ;;
    --tls) tls="$2"; shift 2 ;;
    --output) out="$2"; shift 2 ;;
    *) usage ;;
  esac
done
[[ "$port" =~ ^[0-9]+$ && "$admin_port" =~ ^[0-9]+$ ]] || { echo "--port and --admin-port must be numbers" >&2; exit 2; }
if [[ "$profile" == onprem ]]; then
  dns='^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$'
  [[ "$hostname" =~ $dns ]] || { echo "onprem needs --hostname <dns-name>" >&2; exit 2; }
  admin_hostname="${admin_hostname:-admin.$hostname}"
  [[ "$admin_hostname" =~ $dns && "$admin_hostname" != "$hostname" ]] ||
    { echo "--admin-hostname must be a DNS name different from --hostname" >&2; exit 2; }
fi
[[ -e "$out" ]] && { echo "refusing to overwrite existing $out (move it away first; it holds this environment's secrets)" >&2; exit 1; }
command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

hex() { openssl rand -hex "$1"; }
if [[ "$profile" == local ]]; then url="http://localhost:$port"; admin_url="http://localhost:$admin_port"
else url="https://$hostname"; admin_url="https://$admin_hostname"; fi

umask 077
{
  echo "# Generated by scripts/setup/new-env.sh ($profile) on $(date -u +%FT%TZ). Contains secrets: never commit or share."
  echo "DOMAIN_CLIENT=$url"
  echo "DOMAIN_SERVER=$url"
  echo "ADMIN_PANEL_URL=$admin_url"
  echo "ADMIN_PANEL_SESSION_SECRET=$(hex 32)"
  echo "CREDS_KEY=$(hex 32)"
  echo "CREDS_IV=$(hex 16)"
  echo "JWT_SECRET=$(hex 32)"
  echo "JWT_REFRESH_SECRET=$(hex 32)"
  echo "MONGO_ROOT_USERNAME=root$(hex 4)"
  echo "MONGO_ROOT_PASSWORD=$(hex 24)"
  echo "MONGO_APP_USERNAME=librechat"
  echo "MONGO_APP_PASSWORD=$(hex 24)"
  echo "MEILI_MASTER_KEY=$(hex 32)"
  echo "# Optional: API key of the approved Qwen endpoint (#37). Empty = no model; chats end with a generic error."
  echo "QWEN_API_KEY="
  if [[ "$profile" == local ]]; then
    echo "LOCAL_HTTP_PORT=$port"
    echo "LOCAL_ADMIN_PORT=$admin_port"
  else
    echo "EFAIW_HOSTNAME=$hostname"
    echo "EFAIW_ADMIN_HOSTNAME=$admin_hostname"
    echo "EFAIW_TLS=$tls"
  fi
} > "$out"
echo "Wrote $out ($profile). Next: see docs/operations/$([[ "$profile" == local ]] && echo windows-local || echo ubuntu-onprem).md"
